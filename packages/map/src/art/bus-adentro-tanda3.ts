/**
 * Asiento de pasajero mirando hacia +x (de espaldas, `back`): concha de plástico moldeado verde lima con el
 * cojín negro y sus costuras, o el azul de los preferenciales con su tela; el agarradero amarillo encima.
 */
export function busSeatSprite(back: boolean, blue: boolean): Sprite {
  const l = busLegend();
  const legend: Legend = blue ? { ...l, ...BLUE_SHELL, O: edgeOf(C.blue, 0.5) } : l;
  const g = back ? ASIENTO_B : ASIENTO;
  return gridSprite(g.rows, legend, g.ox, g.oy);
}

