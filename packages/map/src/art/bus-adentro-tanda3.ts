// El Megabús por dentro dibujado a mano (docs/arte/estandar-arte.md): la barra con timbre, la cabina del
// conductor y el plato del fuelle, en grillas de letras. Leyenda común: los dígitos 0..6 son el verde lima
// de la carrocería; a..e el caucho negro; g..l el gris del metal y del fuelle; V..Z el amarillo de las
// barras; P..T el vidrio polarizado (p, q, r, t, el mismo vidrio dejando ver detrás); A..F el rojo del
// timbre y del extintor; L..N el ámbar de los LED; m, n la pantallita azul; u..w el crema de las etiquetas.
// Los contornos son cálidos y del material: `o` del negro y el gris, `O` del lima, `U` del amarillo, `H`
// del rojo; `s` es la sombra en el piso. Cada grilla trae dónde queda el origen del mueble.
import { BLACK, GREY, HANDRAIL, LED, LIME, TINT } from "./bus-colores";
import { edgeOf, gridSprite, groundShadow, rampLegend, type Legend } from "./grilla";
import { C, mix } from "./palette";
import { alpha, at, type Sprite } from "./pixel";

function busLegend(): Legend {
  return {
    ...rampLegend(LIME, "0123456"),
    ...rampLegend(BLACK, "abcde"),
    ...rampLegend(GREY, "ghijkl"),
    ...rampLegend(HANDRAIL, "VWXYZ"),
    ...rampLegend(TINT, "PQRST"),
    p: alpha(at(TINT, 0), 0.7),
    q: alpha(at(TINT, 1), 0.55),
    r: alpha(at(TINT, 3), 0.6),
    t: alpha(mix(at(TINT, 4), at(C.cream, 4), 0.35), 0.6),
    ...rampLegend(C.rug, "ABCDEF"),
    L: at(LED, 2),
    M: at(LED, 3),
    N: at(LED, 4),
    m: at(C.screen, 3),
    n: at(C.screen, 4),
    u: at(C.cream, 2),
    v: at(C.cream, 4),
    w: at(C.cream, 5),
    o: edgeOf(GREY, 0.55),
    O: edgeOf(LIME, 0.5),
    U: edgeOf(HANDRAIL, 0.45),
    H: edgeOf(C.rug, 0.45),
    s: groundShadow(0.3),
  };
}

type Grid = { rows: readonly string[]; ox: number; oy: number };
const sprite = (g: Grid): Sprite => gridSprite(g.rows, busLegend(), g.ox, g.oy);

